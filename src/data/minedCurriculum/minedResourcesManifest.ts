function formatBytes(bytes: number): string {
  if (!bytes || bytes <= 0) return 'N/D (Enlace Oficial)';
  const mb = bytes / (1024 * 1024);
  if (mb >= 1) return `${mb.toFixed(1)} MB`;
  const kb = bytes / 1024;
  return `${kb.toFixed(0)} KB`;
}

function inferDocType(filename: string, url: string): MinedResourceDocType {
  const lower = `${filename} ${url}`.toLowerCase();
  if (lower.endsWith('.jpeg') || lower.endsWith('.jpg') || lower.includes('mensaje institucional')) {
    return 'Infografía';
  }
  if (lower.includes('programa de estudio') || lower.includes('programas de estudio') || lower.includes('programa ') || lower.includes('marco curricular')) {
    return 'Programa de Estudio';
  }
  if (lower.includes('cuaderno de trabajo') || lower.includes('cuaderno de ejercicios')) {
    return 'Cuaderno de Ejercicios';
  }
  if (lower.includes('guía metodológica') || lower.includes('guia metodologica') || lower.includes('guia_metodologica') || lower.includes('guia-metodológica') || lower.includes('gm_desarrollo corporal')) {
    return 'Guía Metodológica';
  }
  if (lower.includes('lectoescritura') || lower.includes('orientaciones para la familia')) {
    return 'Cuadernillo';
  }
  return 'Libro de Texto';
}

